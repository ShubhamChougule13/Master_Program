public class Exercise5 {
    // Variable assignment and increment and printing
    public static void main(String[] args) {
        int a = 10;
        System.out.println(a);
        a = a + 2;
        System.out.println(a);
        a = a * 2;
        System.out.println(a);
        a = a - 2;
        System.out.println(a);

    }
}
